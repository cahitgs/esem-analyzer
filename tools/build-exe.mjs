// tools/build-exe.mjs — packages the app and its local Mplus runner into ONE Windows executable
// (Node "single executable application"): dist/ESEM-Analyzer.exe. Double-click it on a computer with
// Mplus: it serves the app from embedded files, opens the browser, runs models, nothing to install.
//   node tools/build-exe.mjs            → dist/ESEM-Analyzer.exe
//   node tools/build-exe.mjs --name X   → dist/X.exe
// Needs Node 20.12+ on the build machine (the exe embeds this very Node runtime) and network access the
// first time (postject, the tool that injects the blob, is fetched by npx).
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync, spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const argName = process.argv.indexOf('--name');
const NAME = argName > 0 ? process.argv[argName + 1] : 'ESEM-Analyzer';
const SERVER = path.join(ROOT, 'serve.mjs');
// what the exe serves: the app shell, styles, modules, fonts, the guided demo and its pictures, the example data
const INCLUDE = ['index.html', 'demo.html', 'css', 'js', 'example-dataset', 'docs/img'];
const EXT = new Set(['.html', '.css', '.js', '.mjs', '.json', '.csv', '.dat', '.out', '.inp', '.txt', '.md', '.svg', '.png', '.jpg', '.jpeg', '.webp', '.ico', '.woff', '.woff2']);
const FUSE = 'NODE_SEA_FUSE_fce680ab2cc467b6e072b8b5df1996b2';

const BUILD = path.join(ROOT, 'build');
const DIST = path.join(ROOT, 'dist');
fs.mkdirSync(BUILD, { recursive: true });
fs.mkdirSync(DIST, { recursive: true });

// ---- 1 · collect the static files -------------------------------------------------------------
const assets = {};
function add(rel) {
  const abs = path.join(ROOT, rel);
  if (!fs.existsSync(abs)) { console.warn(`  skip (missing): ${rel}`); return; }
  const st = fs.statSync(abs);
  if (st.isDirectory()) { for (const f of fs.readdirSync(abs)) add(path.posix.join(rel, f)); return; }
  if (!EXT.has(path.extname(rel).toLowerCase())) return;
  assets[rel.replace(/\\/g, '/')] = abs;
}
INCLUDE.forEach(add);
const keys = Object.keys(assets).sort();
fs.writeFileSync(path.join(BUILD, 'assets.json'), JSON.stringify(keys));
const total = keys.reduce((n, k) => n + fs.statSync(assets[k]).size, 0);
console.log(`  ${keys.length} files, ${(total / 1048576).toFixed(1)} MB to embed`);

// ---- 2 · the entry: serve.mjs rewritten as CommonJS (SEA needs a CommonJS main) + the asset table ----
let code = fs.readFileSync(SERVER, 'utf8');
code = code
  .replace(/^import (\w+) from '(node:[\w/]+)';$/gm, "const $1 = require('$2');")
  .replace(/^import \{([^}]+)\} from '(node:[\w/]+)';$/gm, "const {$1} = require('$2');")
  .replace(/fileURLToPath\(import\.meta\.url\)/g, 'process.execPath');
if (/^\s*(import|export)\s/m.test(code)) throw new Error('serve.mjs still contains import/export statements the build cannot convert.');
const entry = `'use strict';
// generated by tools/build-exe.mjs — do not edit
const __sea = require('node:sea');
const __keys = JSON.parse(__sea.getAsset('__assets__', 'utf8'));
globalThis.__SEA__ = { assets: new Map(__keys.map((k) => [k, () => Buffer.from(__sea.getAsset(k))])) };
${code}`;
const entryPath = path.join(BUILD, 'entry.cjs');
fs.writeFileSync(entryPath, entry);

// ---- 3 · the SEA blob -----------------------------------------------------------------------------
const blobPath = path.join(BUILD, 'sea-prep.blob');
const cfg = { main: entryPath, output: blobPath, disableExperimentalSEAWarning: true, useCodeCache: true, assets: { __assets__: path.join(BUILD, 'assets.json'), ...assets } };
const cfgPath = path.join(BUILD, 'sea-config.json');
fs.writeFileSync(cfgPath, JSON.stringify(cfg, null, 2));
console.log('  generating the blob …');
execFileSync(process.execPath, ['--experimental-sea-config', cfgPath], { stdio: 'inherit', cwd: ROOT });

// ---- 4 · copy this Node runtime and inject the blob --------------------------------------------
const exePath = path.join(DIST, `${NAME}${process.platform === 'win32' ? '.exe' : ''}`);
fs.copyFileSync(process.execPath, exePath);
console.log('  injecting the blob with postject …');
// npx is a .cmd on Windows, so it runs through a shell; the command is one quoted string (paths may contain spaces)
const q = (s) => `"${s}"`;
const r = spawnSync(`npx --yes postject ${q(exePath)} NODE_SEA_BLOB ${q(blobPath)} --sentinel-fuse ${FUSE}`, { stdio: 'inherit', cwd: ROOT, shell: true });
if (r.status !== 0) throw new Error(`postject failed (exit ${r.status})`);
const mb = (fs.statSync(exePath).size / 1048576).toFixed(0);
console.log(`\n  ready: ${exePath} (${mb} MB, Node ${process.version} inside)`);
console.log('  run it: double-click, or from a terminal  ' + path.basename(exePath) + ' [port] [--no-open]');
